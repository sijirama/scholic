/**
 * highlighter.ts — Renders and manages text highlights in the DOM.
 *
 * When an annotation is created or re-anchored, we wrap the relevant text nodes
 * in <scholic-highlight> custom elements. Using a custom element name (not <span>)
 * reduces the chance of page CSS interfering with our highlights.
 *
 * Key algorithm: `wholeTextNodesInRange` splits text nodes at range boundaries
 * using `splitText()` so only the exact selected text is highlighted — not
 * the entire containing text node.
 *
 * Adapted from Hypothesis client (MIT license).
 */

import { isNodeInRange } from './range-util';

/** Extended HTMLElement with annotation metadata */
export type HighlightElement = HTMLElement & {
  /** The annotation ID this highlight belongs to */
  _scholicAnnotationId?: string;
};

/**
 * Return text nodes which are entirely inside `range`.
 *
 * If a range starts or ends part-way through a text node, the node is split
 * and the part inside the range is returned.
 *
 * This is the KEY function that fixes paragraph-level highlighting.
 * Without splitting, a text node that contains "Hello world" where only
 * "world" is selected would still result in "Hello world" being highlighted.
 *
 * Ported from Hypothesis client's `wholeTextNodesInRange`.
 */
function wholeTextNodesInRange(range: Range): Text[] {
  if (range.collapsed) {
    // Exit early for an empty range to avoid an edge case that breaks the
    // algorithm below. Splitting a text node at the start of an empty range
    // can leave the range ending in the left part rather than the right part.
    return [];
  }

  let root = range.commonAncestorContainer as Node | null;
  if (root && root.nodeType !== Node.ELEMENT_NODE) {
    // If the common ancestor is not an element, set it to the parent element to
    // ensure that the loop below visits any text nodes generated by splitting
    // the common ancestor.
    root = root.parentElement;
  }
  if (!root) {
    return [];
  }

  const textNodes: Text[] = [];
  const nodeIter = root.ownerDocument!.createNodeIterator(
    root,
    NodeFilter.SHOW_TEXT, // Only return Text nodes
  );
  let node: Node | null;

  while ((node = nodeIter.nextNode())) {
    if (!isNodeInRange(range, node)) {
      continue;
    }
    const text = node as Text;

    if (text === range.startContainer && range.startOffset > 0) {
      // Split `text` where the range starts. The split will create a new Text
      // node which will be in the range and will be visited in the next
      // loop iteration.
      text.splitText(range.startOffset);
      continue;
    }

    if (text === range.endContainer && range.endOffset < text.data.length) {
      // Split `text` where the range ends, leaving it as the part in the range.
      text.splitText(range.endOffset);
    }

    textNodes.push(text);
  }

  return textNodes;
}

/**
 * Wrap text nodes within a Range with <scholic-highlight> elements.
 *
 * Uses `wholeTextNodesInRange` to split text nodes at boundaries so only
 * the exact selected portion is highlighted.
 *
 * @param range - The DOM Range to highlight
 * @param cssClass - Additional CSS class ('scholic-annotation' or 'scholic-private')
 * @param annotationId - Optional annotation ID to associate with the highlight
 * @returns Array of created highlight elements
 */
export function highlightRange(
  range: Range,
  cssClass: string = 'scholic-annotation',
  annotationId?: string,
): HighlightElement[] {
  const textNodes = wholeTextNodesInRange(range);

  if (textNodes.length === 0) {
    return [];
  }

  // Group adjacent text nodes into spans (reduces number of highlight elements).
  // Adjacent text nodes sharing the same parent can be wrapped in one element.
  const textNodeSpans: Text[][] = [];
  let currentSpan: Text[] | null = null;
  let prevNode: Node | null = null;

  textNodes.forEach((node) => {
    if (prevNode && prevNode.nextSibling === node) {
      currentSpan!.push(node);
    } else {
      currentSpan = [node];
      textNodeSpans.push(currentSpan);
    }
    prevNode = node;
  });

  // Filter out text node spans that consist only of white space. This avoids
  // inserting highlight elements in places that can only contain a restricted
  // subset of nodes such as table rows and lists.
  const whitespace = /^\s*$/;
  const filteredSpans = textNodeSpans.filter((span) => {
    const parentElement = span[0].parentElement;
    return (
      // Whitespace <span>s should be highlighted since they affect layout in
      // some code editors
      (parentElement?.childNodes.length === 1 &&
        parentElement?.tagName === 'SPAN') ||
      // Otherwise ignore white-space only Text node spans
      span.some((node) => !whitespace.test(node.data))
    );
  });

  // Create a <scholic-highlight> element for each span of text nodes
  const highlights: HighlightElement[] = [];

  filteredSpans.forEach((nodes) => {
    const highlightEl = document.createElement(
      'scholic-highlight',
    ) as HighlightElement;
    highlightEl.className = `scholic-highlight ${cssClass}`;

    if (annotationId) {
      highlightEl._scholicAnnotationId = annotationId;
      highlightEl.dataset.annotationId = annotationId;
    }

    // Replace the first text node with the highlight element,
    // then move all the text nodes inside it
    const parent = nodes[0].parentNode!;
    parent.replaceChild(highlightEl, nodes[0]);
    nodes.forEach((node) => highlightEl.appendChild(node));

    highlights.push(highlightEl);
  });

  return highlights;
}

/**
 * Remove highlight elements and restore the original DOM structure.
 * The text nodes are moved back to their original positions.
 *
 * @param highlights - Array of highlight elements to remove
 */
export function removeHighlights(highlights: HighlightElement[]): void {
  for (const h of highlights) {
    if (h.parentNode) {
      // Move all child nodes (the original text) back into the parent
      const children = Array.from(h.childNodes);
      const parent = h.parentNode;
      children.forEach((child) => parent.insertBefore(child, h));
      parent.removeChild(h);
      // Merge adjacent text nodes that were split
      parent.normalize();
    }
  }
}

/**
 * Find all highlight elements for a given annotation ID.
 *
 * @param annotationId - The annotation to search for
 * @returns Array of matching highlight elements
 */
export function getHighlightsForAnnotation(
  annotationId: string,
): HighlightElement[] {
  return Array.from(
    document.querySelectorAll(
      `scholic-highlight[data-annotation-id="${annotationId}"]`,
    ),
  ) as HighlightElement[];
}
